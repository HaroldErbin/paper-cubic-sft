def melem2(A: np.ndarray, Nb: int, Nk: int, l, lp) -> float:
    """<phi(l)|_{Nb} A |phi(l')>_{Nk} for A mapping level Nk to level Nb."""
    v = coherent(pol(Pf, l, a1, a2), Nb)
    w = coherent(pol(Pf, lp, b1, b2), Nk)
    return float(v @ GRAM[Nb] @ A @ w)


def rel_move2(A: np.ndarray, Nb: int, Nk: int) -> float:
    """rel_move for a level-changing operator, Cauchy-Schwarz scale |v_Nb| |w_Nk|."""
    x = melem2(A, Nb, Nk, lf, lpf)
    ys = [
        melem2(A, Nb, Nk, lf + 0.7 * uf, lpf),
        melem2(A, Nb, Nk, lf, lpf - 0.9 * upf),
    ]
    v = coherent(pol(Pf, lf, a1, a2), Nb)
    w = coherent(pol(Pf, lpf, b1, b2), Nk)
    scale = math.sqrt(float(v @ GRAM[Nb] @ v) * float(w @ GRAM[Nk] @ w))
    return max(abs(x - y) for y in ys) / scale


