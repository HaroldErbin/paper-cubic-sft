# ---------------------------------------------------------------------------
# C3.5 -- sl(2) lemma: matrix elements of sl(2)-isotypic projectors between
# tachyon-pair coherent states carry no l^2, l'^2
# ---------------------------------------------------------------------------
# Truncated chiral Fock space of d = 3 free bosons (Euclidean, alpha' = 2 so
# alpha_0 = P), modes n = 1..NMAX. Coherent state of the pair at a1, a2:
# exp(sum_n alpha_{-n} . v_n / n)|P>, v_n = P/2 (a1^n + a2^n) + l (a1^n - a2^n)
# (the circle state of e^{ik_1 X}(a1) e^{ik_2 X}(a2), k_{1,2} = P/2 +- l,
# stripped of its l^2-carrying scalar prefactor). The weight-(h_P + n) part at
# level N is L_{-1}^{N-n} (ker L_1 at level n); its orthogonal projector Pi_{N,n}
# (L_n^dagger = L_{-n}) and the Moebius operators L_{+-1} generate the operators
# acting trivially on the sl(2) multiplicity spaces (the projectors alone give
# the level-preserving part only; L_{+-1} legs added below, critic #N5).
D_FOCK, NMAX = 3, 4
MODES = [(n, mu) for n in range(1, NMAX + 1) for mu in range(D_FOCK)]


def fock_basis(N: int) -> list[tuple[int, ...]]:
    out: list[tuple[int, ...]] = []

    def rec(i: int, rem: int, occ: list[int]) -> None:
        if i == len(MODES):
            if rem == 0:
                out.append(tuple(occ))
            return
        n = MODES[i][0]
        for k in range(rem // n + 1):
            rec(i + 1, rem - k * n, occ + [k])

    rec(0, N, [])
    return out


FB = {N: fock_basis(N) for N in range(NMAX + 1)}
FIDX = {N: {b: i for i, b in enumerate(FB[N])} for N in FB}
GRAM = {
    N: np.diag(
        [
            math.prod(MODES[i][0] ** k * math.factorial(k) for i, k in enumerate(b))
            for b in FB[N]
        ]
    )
    for N in FB
}


def alpha(n: int, mu: int, N: int) -> np.ndarray | None:
    """Matrix of alpha_n^mu (n != 0) from level N to level N - n."""
    M = N - n
    if M < 0 or M > NMAX:
        return None
    A = np.zeros((len(FB[M]), len(FB[N])))
    i = MODES.index((abs(n), mu))
    for j, b in enumerate(FB[N]):
        b2 = list(b)
        if n < 0:
            b2[i] += 1
            c = 1.0
        else:
            if b2[i] == 0:
                continue
            c = float(n * b2[i])
            b2[i] -= 1
        A[FIDX[M][tuple(b2)], j] += c
    return A


def virasoro(k: int, N: int, P: np.ndarray) -> np.ndarray:
    """Matter L_k (k = -1, 1, 2) from level N to N - k: sum_m :alpha_{k-m}.alpha_m:/2."""
    A = np.zeros((len(FB[N - k]), len(FB[N])))
    for mu in range(D_FOCK):
        for m in range(-NMAX, NMAX + 1):
            n1, n2 = k - m, m  # term alpha_{n1} alpha_{n2}, normal ordered
            if n1 > n2:
                continue  # count each unordered pair once, below
            coef = 0.5 if n1 == n2 else 1.0
            if n1 == 0 and n2 == 0:
                continue

            # rightmost annihilator acts first (normal order: larger index right)
            def ap(n: int, lev: int) -> np.ndarray | None:
                if n == 0:
                    return P[mu] * np.eye(len(FB[lev]))
                return alpha(n, mu, lev)

            a2 = ap(n2, N)
            if a2 is None:
                continue
            a1 = ap(n1, N - n2)
            if a1 is None:
                continue
            A += coef * (a1 @ a2)
    return A


def coherent(v: list[np.ndarray], N: int) -> np.ndarray:
    return np.array(
        [
            math.prod(
                (v[n - 1][mu] / n) ** k / math.factorial(k)
                for (n, mu), k in zip(MODES, b)
            )
            for b in FB[N]
        ]
    )


def iso_projector(N: int, n: int, P: np.ndarray, single: bool = False) -> np.ndarray:
    X = null_space_np(virasoro(1, n, P)) if n > 0 else np.ones((1, 1))
    if single:
        X = X[:, :1]  # one quasi-primary direction only: not sl(2)-isotypic
    for k in range(n, N):
        X = virasoro(-1, k, P) @ X
    g = GRAM[N]
    return X @ np.linalg.solve(X.T @ g @ X, X.T @ g)


def pol(P, l, a1: float, a2: float) -> list[np.ndarray]:
    return [P / 2 * (a1**n + a2**n) + l * (a1**n - a2**n) for n in range(1, NMAX + 1)]


Pf = rng.normal(size=D_FOCK)
lf = rng.normal(size=D_FOCK)
lpf = rng.normal(size=D_FOCK)
a1, b1 = rng.uniform(0.5, 0.9, 2)
a2, b2 = -rng.uniform(0.5, 0.9, 2)
