def melem(A: np.ndarray, N: int, l, lp) -> float:
    v = coherent(pol(Pf, l, a1, a2), N)
    w = coherent(pol(Pf, lp, b1, b2), N)
    return float(v @ GRAM[N] @ A @ w)


def rel_move(A: np.ndarray, N: int) -> float:
    """Change of the matrix element under l^2, l'^2 moves, relative to the
    Cauchy-Schwarz scale |v| |w| of the level-N components."""
    x = melem(A, N, lf, lpf)
    ys = [melem(A, N, lf + 0.7 * uf, lpf), melem(A, N, lf, lpf - 0.9 * upf)]
    v = coherent(pol(Pf, lf, a1, a2), N)
    w = coherent(pol(Pf, lpf, b1, b2), N)
    scale = math.sqrt(float(v @ GRAM[N] @ v) * float(w @ GRAM[N] @ w))
    return max(abs(x - y) for y in ys) / scale


