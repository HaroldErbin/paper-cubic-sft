# ---------------------------------------------------------------------------
# C3.7 -- first order in a non-Moebius (L_{+-2}) cut dressing: the mixed
# l^2 l'^2 dependence of the log of the sewing side vanishes identically
# ---------------------------------------------------------------------------
# Around a level-diagonal base kernel (weights d_N), the O(eps) correction is
# K1 = sum_N e_N <phi|_{N-2} L_2 |phi'>_N + f_N <phi|_N L_{-2} |phi'>_{N-2};
# d ln K / d eps at eps = 0 is K1 / K0. Claim (critic #N2): K1/K0 is affine in
# (l^2, l'^2) at fixed P.l, P.l', l.l', so its mixed second difference is zero.
# Break: the second-order cross term <phi|_N L_{-2} L_2 |phi'>_N has a nonzero
# mixed second difference. (l, l') are built from the invariants in d = 3.
def pair_from_invariants(A2: float, B2_: float, x: float, xp: float, C: float):
    """(l, l') in R^3 with P = |P| e_1: P.l = |P| x, P.l' = |P| x', l.l' = C,
    l^2 = A2, l'^2 = B2_."""
    r, rp = math.sqrt(A2 - x**2), math.sqrt(B2_ - xp**2)
    ca = (C - x * xp) / (r * rp)
    l_ = np.array([x, r * ca, r * math.sqrt(1 - ca**2)])
    lp_ = np.array([xp, rp, 0.0])
    return l_, lp_


P_e1 = np.array([np.linalg.norm(Pf), 0.0, 0.0])
d_w, e_w, f_w, g_w = (rng.uniform(0.5, 1.5, NMAX + 1) for _ in range(4))
Lm2_42 = np.linalg.solve(GRAM[4], virasoro(2, 4, P_e1).T @ GRAM[2])  # 2 -> 4
L2_mats = {N: virasoro(2, N, P_e1) for N in (2, 3, 4)}
Lm2_mats = {N: np.linalg.solve(GRAM[N], L2_mats[N].T @ GRAM[N - 2]) for N in L2_mats}


def sewing_orders(l_, lp_) -> tuple[float, float, float]:
    """(K0, K1, K2cross) on the truncated chiral space, levels <= 4."""
    v = {N: coherent(pol(P_e1, l_, a1, a2), N) for N in FB}
    w = {N: coherent(pol(P_e1, lp_, b1, b2), N) for N in FB}
    k0 = sum(d_w[N] * float(v[N] @ GRAM[N] @ w[N]) for N in FB)
    k1 = sum(
        e_w[N] * float(v[N - 2] @ GRAM[N - 2] @ L2_mats[N] @ w[N])
        + f_w[N] * float(v[N] @ GRAM[N] @ Lm2_mats[N] @ w[N - 2])
        for N in L2_mats
    )
    k2 = sum(
        g_w[N] * float(v[N] @ GRAM[N] @ Lm2_mats[N] @ L2_mats[N] @ w[N])
        for N in L2_mats
    )
    return k0, k1, k2


def mixed_second_difference(fun, A0, B0, dA, dB, x, xp, C) -> tuple[float, float]:
    vals = {}
    for i, j in itertools.product((0, 1), repeat=2):
        vals[i, j] = fun(*pair_from_invariants(A0 + i * dA, B0 + j * dB, x, xp, C))
    mix = vals[1, 1] - vals[1, 0] - vals[0, 1] + vals[0, 0]
    return mix, max(abs(t) for t in vals.values())


inv = dict(A0=1.3, B0=1.1, dA=0.4, dB=0.3, x=0.35, xp=-0.25, C=0.2)
mix1, sc1 = mixed_second_difference(
    lambda l_, lp_: sewing_orders(l_, lp_)[1] / sewing_orders(l_, lp_)[0], **inv
)
mix2, sc2 = mixed_second_difference(
    lambda l_, lp_: sewing_orders(l_, lp_)[2] / sewing_orders(l_, lp_)[0], **inv
)
# the first order is not trivially zero: K1/K0 does move with l'^2 alone
one_sided = abs(
    (lambda p: sewing_orders(*p)[1] / sewing_orders(*p)[0])(
        pair_from_invariants(1.3, 1.4, 0.35, -0.25, 0.2)
    )
    - (lambda p: sewing_orders(*p)[1] / sewing_orders(*p)[0])(
        pair_from_invariants(1.3, 1.1, 0.35, -0.25, 0.2)
    )
)
report(
    "C3.7-first-order-mixed-zero",
    bool(abs(mix1) / sc1 < 1e-12 and abs(mix2) / sc2 > 1e-6 and one_sided > 1e-6),
    f"O(eps) K1/K0 mixed 2nd difference in (l^2, l'^2): {abs(mix1) / sc1:.1e} "
    f"(rel.); K1/K0 moves with l'^2 alone by {one_sided:.2e}; break: second-order "
    f"cross term L_-2 L_2 mixed difference {abs(mix2) / sc2:.2e} (rel.)",
)

