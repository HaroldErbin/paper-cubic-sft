# ---------------------------------------------------------------------------
# C3.2 -- (l, l')-dependence of the rigid four-tachyon element, from positions
# ---------------------------------------------------------------------------
# Glued sphere of two rigid halves (R80 annotation): punctures at +-2 beta
# (left half) and +-2 beta y (right half, y = q / 4 beta^2); the right legs'
# coordinate discs scale with |y|, so a weight-(h, h) primary there carries
# |y|^{2h} (h = alpha' k^2 / 4, matter part; the ghost part is l-independent).
# Matter correlator: prod_{i<j} |z_ij|^{alpha' k_i . k_j}, mostly-plus metric.
ETA4 = np.diag([-1.0, 1.0, 1.0, 1.0])


def dot4(a: np.ndarray, b: np.ndarray) -> float:
    return float(a @ ETA4 @ b)


def log_rigid(q: complex, P, l, lp, leg_sign: float = 1.0) -> float:
    """ln of the l-dependent part of the rigid element at q, from positions."""
    ks = [P / 2 + l, P / 2 - l, -P / 2 + lp, -P / 2 - lp]
    y = q / (4 * B2)
    zs = [2 * BETA, -2 * BETA, 2 * BETA * y, -2 * BETA * y]
    out = 0.0
    for i, j in itertools.combinations(range(4), 2):
        out += dot4(ks[i], ks[j]) * math.log(abs(zs[i] - zs[j]))  # alpha' = 1
    for i in (2, 3):
        out += leg_sign * 2 * (dot4(ks[i], ks[i]) / 4) * math.log(abs(y))
    return out


def q_part(P, l, lp, q1: complex, q2: complex, leg_sign: float = 1.0) -> float:
    return log_rigid(q1, P, l, lp, leg_sign) - log_rigid(q2, P, l, lp, leg_sign)


def q_part_formula(P, l, lp, q1: complex, q2: complex) -> float:
    """record 110 (3.2)-(3.3): |y|^{P^2/2} |1-y|^{2a_-} |1+y|^{2a_+}, matter part."""
    two_am = -dot4(P, P) / 2 + 2 * dot4(l, lp)
    two_ap = -dot4(P, P) / 2 - 2 * dot4(l, lp)

    def g(q: complex) -> float:
        y = q / (4 * B2)
        return (
            dot4(P, P) / 2 * math.log(abs(y))
            + two_am * math.log(abs(1 - y))
            + two_ap * math.log(abs(1 + y))
        )

    return g(q1) - g(q2)


def orth_dir(P, lp) -> np.ndarray:
    """A direction u with P.u = l'.u = 0 (mostly-plus), so l -> l + t u keeps
    P.l and l.l' fixed and moves l^2."""
    A = np.stack([ETA4 @ P, ETA4 @ lp])
    u = null_space_np(A)[:, 0]
    return u


def null_space_np(A: np.ndarray) -> np.ndarray:
    _, sv, vt = np.linalg.svd(A)
    rank = int((sv > 1e-12).sum())
    return vt[rank:].T


